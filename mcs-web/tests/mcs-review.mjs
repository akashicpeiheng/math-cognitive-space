import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { startTestServer } from './helpers.mjs';
import { CHROME_PATH, PLAYWRIGHT_SPECIFIER } from './browser-runtime.mjs';
import { MCS_STORAGE_KEY } from '../shared/mcs-space.mjs';

const app = await startTestServer({ lean: { enabled: false } });
const { chromium } = await import(PLAYWRIGHT_SPECIFIER);
const browser = await chromium.launch({ executablePath: CHROME_PATH ?? undefined, headless: true });
const errors = [], checks = [];
const observe = page => {
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
};
const ready = async page => { await page.locator('[data-mcs-canvas]').waitFor(); await page.waitForTimeout(250); };
const camera = page => page.locator('[data-mcs-canvas]').evaluate(el => ({ scale: Number(el.dataset.zoom), x: Number(el.dataset.cameraX), y: Number(el.dataset.cameraY) }));
mkdirSync('runtime/mcs-qa', { recursive: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(); observe(page);
  await page.goto(app.origin + '/mcs?view=objects'); await ready(page);
  await page.getByRole('combobox', { name: '显示层级' }).selectOption('1');
  await page.locator('[data-mcs-region="obj:group:subdiscipline"]').waitFor();
  const grip = await page.locator('[data-mcs-region="obj:group:subdiscipline"] .mcs-region-grip').boundingBox();
  await page.mouse.move(grip.x + 25, grip.y + 12); await page.mouse.down();
  await page.mouse.move(grip.x + 75, grip.y + 35); await page.mouse.up();
  await page.locator('[data-mcs-box="obj:group:topic"]').focus(); await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('.mcs-inspector h2')?.textContent.includes('代数结构的映射表示'));
  checks.push('drag followed by keyboard inspection');
  await page.getByRole('button', { name: '分享视图', exact: true }).click();
  const share = await page.getByRole('textbox', { name: '公共视图链接' }).inputValue();
  const shared = JSON.parse(decodeURIComponent(new URL(share).hash.slice(5)));
  assert(shared.viewport?.width > 500);
  const other = await context.newPage(); observe(other); await other.goto(share); await ready(other);
  await other.getByRole('button', { name: '放大', exact: true }).click();
  const edited = await camera(other);
  // Deliberately navigate before the 180ms persistence debounce completes.
  await other.locator('.mcs-inspector').getByRole('link', { name: '完整对象与证据 ↗' }).click();
  await other.goBack(); await ready(other);
  assert.deepEqual(await camera(other), edited, 'Back restores this history entry, not the original share hash');
  await other.reload(); await ready(other); assert.deepEqual(await camera(other), edited);
  await other.locator('.mcs-inspector').getByRole('link', { name: '完整对象与证据 ↗' }).click();
  await other.getByRole('link', { name: '← 返回 MCS 视图' }).click(); await ready(other);
  assert.deepEqual(await camera(other), edited, 'explicit return retains edits made after opening a share');
  await other.reload(); await ready(other); assert.deepEqual(await camera(other), edited);
  const fresh = await context.newPage(); observe(fresh); await fresh.goto(share); await ready(fresh);
  const freshState = await fresh.evaluate(key => JSON.parse(localStorage.getItem(key)), MCS_STORAGE_KEY);
  const expectedShareScale = shared.camera.scale * Math.min(freshState.viewport.width / shared.viewport.width, freshState.viewport.height / shared.viewport.height);
  assert.equal((await camera(fresh)).scale, Number(expectedShareScale.toFixed(4)), 'new share entry overrides local storage and fits the current canvas');
  await fresh.close(); await other.close();
  checks.push('share priority, edited share Back and refresh');
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const mobilePage = await mobile.newPage(); observe(mobilePage); await mobilePage.goto(share); await ready(mobilePage);
  const restored = await mobilePage.evaluate(key => JSON.parse(localStorage.getItem(key)), MCS_STORAGE_KEY);
  const centre = state => ({ x: (state.viewport.width / 2 - state.camera.x) / state.camera.scale, y: (state.viewport.height / 2 - state.camera.y) / state.camera.scale });
  const a = centre(shared), b = centre(restored);
  assert(Math.abs(a.x - b.x) < .01 && Math.abs(a.y - b.y) < .01, 'cross-screen share retains world centre');
  assert(restored.camera.scale < shared.camera.scale, 'shared desktop framing scales to mobile');
  const canvas = await mobilePage.locator('[data-mcs-canvas]').boundingBox(), panel = await mobilePage.locator('.mcs-inspector').boundingBox();
  assert(canvas.y + canvas.height <= panel.y + 1, 'bottom sheet does not cover the canvas');
  assert(panel.y + panel.height <= 844, 'bottom sheet stays within the viewport');
  await mobilePage.screenshot({ path: 'runtime/mcs-qa/review-mobile.png', fullPage: true });
  await mobilePage.goto(app.origin + '/en/mcs?view=objects'); await ready(mobilePage);
  await mobilePage.setViewportSize({ width: 320, height: 568 }); await mobilePage.waitForTimeout(250);
  assert(await mobilePage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert(await mobilePage.evaluate(() => document.querySelector('.mcs-canvas').getBoundingClientRect().bottom <= document.querySelector('.mcs-inspector').getBoundingClientRect().top + 1));
  await mobilePage.screenshot({ path: 'runtime/mcs-qa/review-english-320.png', fullPage: true });
  await mobile.close(); checks.push('390px native touch viewport, 320px English, panel and canvas bounds');

  await page.getByRole('button', { name: '关闭提示', exact: true }).click();
  await page.getByRole('button', { name: '滤镜', exact: true }).click();
  const payload = await (await fetch(app.origin + '/api/v2/ontology/mcs-view')).json();
  const deduction = payload.data.relations.find(r => r.kind === 'deduction' && r.from.id !== r.to.id && r.premises.length > 1);
  assert(deduction, 'real M data contains an AND derivation');
  await page.getByRole('searchbox', { name: '搜索对象与公式' }).fill(deduction.to.id);
  await page.getByRole('combobox', { name: '连线显示' }).selectOption('all');
  const missing = page.locator('.mcs-edge-label[aria-label*="有前提未显示"]').first();
  await missing.waitFor(); await missing.focus(); await page.keyboard.press('Enter');
  await page.locator('.mcs-inspector .content-relation').first().waitFor();
  await page.locator('.mcs-inspector .content-relation summary').first().click();
  assert(await page.locator('.mcs-inspector').innerText().then(text => text.includes('前提')));
  assert(await page.locator('.mcs-inspector .content-relation a').first().getAttribute('href').then(href => href.includes('from=mcs')));
  await page.getByRole('button', { name: '分享视图', exact: true }).click();
  const relationShare = await page.getByRole('textbox', { name: '公共视图链接' }).inputValue();
  const relationPage = await context.newPage(); observe(relationPage); await relationPage.goto(relationShare); await ready(relationPage);
  assert(await relationPage.locator('.mcs-inspector .content-relation').count() > 0, 'shared relation selection is restored');
  await relationPage.close(); await page.getByRole('button', { name: '关闭提示', exact: true }).click();
  await page.keyboard.press('Escape'); assert.equal(await page.locator('.mcs-filters').count(), 0);
  await page.keyboard.press('Escape'); assert.equal(await page.locator('.mcs-inspector').count(), 0);
  checks.push('real filtered AND source remains inspectable; Escape closes panels');

  const motion = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  const motionPage = await motion.newPage(); observe(motionPage); await motionPage.goto(app.origin + '/mcs?view=objects'); await ready(motionPage);
  await motionPage.waitForTimeout(300);
  await motionPage.evaluate(() => {
    window.__mcsFrames = 0;
    const original = window.requestAnimationFrame.bind(window);
    window.requestAnimationFrame = callback => { window.__mcsFrames++; return original(callback); };
  });
  const viewport = await motionPage.locator('[data-mcs-canvas]').boundingBox();
  await motionPage.mouse.move(viewport.x + 10, viewport.y + 70); await motionPage.mouse.wheel(0, -1);
  await motionPage.waitForTimeout(400);
  assert(await motionPage.evaluate(() => window.__mcsFrames <= 2), 'camera-only zoom does not restart 220ms geometry animations');
  await motionPage.emulateMedia({ colorScheme: 'dark' });
  await motionPage.screenshot({ path: 'runtime/mcs-qa/review-dark-desktop.png', fullPage: true });
  await motion.close(); checks.push('normal-motion camera changes do not restart geometry animation; dark theme');
  assert.deepEqual(errors, []);
  writeFileSync('runtime/mcs-qa/review.json', JSON.stringify({ status: 'passed', checks, errors }, null, 2));
  console.log('passed:', checks.join('; '));
} finally { await browser.close(); await app.cleanup(); }
