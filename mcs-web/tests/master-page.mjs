import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { writeFile } from 'node:fs/promises';
import { startTestServer } from './helpers.mjs';
import {loadContentLibrary} from '../core/content-library.mjs';
import { PLAYWRIGHT_SPECIFIER, CHROME_PATH } from './browser-runtime.mjs';

const app = await startTestServer({ lean:{enabled:false} });
let browser;
const errors = [], writes = [];
const artifacts = resolve('tmp/master-mode');
const check = (name, value) => { assert(value, name); console.log(`  ✓ ${name}`); };
try {
  const { chromium } = await import(PLAYWRIGHT_SPECIFIER);
  browser = await chromium.launch({ executablePath:CHROME_PATH ?? undefined, headless:true });
  const context = await browser.newContext({ viewport:{width:1440,height:1000}, reducedMotion:'reduce' });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!['GET','HEAD'].includes(request.method()) && /\/api\/v2\/(profiles|events|notes|learning-plan|tutor)/.test(request.url())) writes.push(request.url()); });
  await page.goto(app.origin + '/nodes/limit%3Alimit-ed', {waitUntil:'networkidle'});
  check('首次打开为普通模式', await page.locator('#reading-mode-select').inputValue() === 'normal');
  check('普通模式保留完整正文', await page.locator('#node-formal-statement').count() === 1);
  await page.evaluate(() => {
    sessionStorage.setItem('mcs-reading-route-v1', JSON.stringify({ synthetic:{id:'synthetic',routeId:'route',goal:'limit:limit-ed',createdAt:'2026-10-19',steps:[{index:1,node:'limit:distance'},{index:2,node:'limit:limit-ed'}]} }));
    sessionStorage.setItem('mcs-reading-progress-v1', JSON.stringify({synthetic:1}));
    localStorage.setItem('master-private-sentinel', 'personal note unchanged');
  });
  await page.locator('#reading-mode-select').selectOption('master');
  await page.locator('.master-node-page').waitFor();
  check('Master 只呈现数学核心', await page.locator('#node-motivation, #node-reading, #node-proof, #node-selfcheck, #node-notes, .learner-actions, .node-footer-actions').count() === 0);
  check('公式由 KaTeX 排版', await page.locator('.master-content .katex').count() > 0);
  check('直觉默认不显示', await page.getByRole('tooltip').count() === 0);
  const tip = page.locator('.master-intuition-trigger').first();
  await tip.hover(); await page.getByRole('tooltip').waitFor();
  check('悬停出现一句直觉', (await page.getByRole('tooltip').innerText()).includes('误差'));
  await page.keyboard.press('Escape');
  check('Escape 关闭提示', await page.getByRole('tooltip').count() === 0);
  await page.mouse.move(0,0); await page.keyboard.press('Tab'); await tip.focus();
  await page.getByRole('tooltip').waitFor();
  check('键盘聚焦可读直觉', await tip.getAttribute('aria-describedby'));
  await page.keyboard.press('Escape');
  await page.goto(app.origin + '/nodes/limit%3Alimit-ed?route=synthetic&step=2', {waitUntil:'networkidle'});
  check('Master 不推进路线阅读进度', await page.evaluate(() => JSON.parse(sessionStorage.getItem('mcs-reading-progress-v1')).synthetic === 1));
  await page.reload({waitUntil:'networkidle'});
  check('刷新保留模式', await page.locator('#reading-mode-select').inputValue() === 'master');
  await page.locator('#theme-select').selectOption('dark');
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await mkdir(artifacts, {recursive:true});
  await page.screenshot({path:resolve(artifacts,'master-limit-dark.png'),fullPage:true});
  check('深色提示面板使用当前主题', await tip.evaluate(el => getComputedStyle(el).backgroundColor !== 'rgb(255, 255, 255)'));

  let detailRequests = 0;
  const countDetails = request => { if (/\/api\/v2\/ontology\/nodes\/[^?]+/.test(request.url())) detailRequests++; };
  page.on('request', countDetails);
  await page.goto(app.origin + '/nodes?case=limit', {waitUntil:'networkidle'});
  check('列表卡片共享压缩内容', await page.locator('[data-master-node] [data-master-content]').count() > 0);
  check('列表不逐卡请求详情', detailRequests === 0);
  page.off('request', countDetails);
  await page.goto(app.origin + '/objects', {waitUntil:'networkidle'});
  check('形式对象与阅读节点列表均有压缩预览', await page.locator('[data-master-content]').count() === loadContentLibrary().objects.length+loadContentLibrary().nodes.length);
  await page.goto(app.origin + '/objects/obj%3Agroup%3Ainjective#claim', {waitUntil:'networkidle'});
  check('形式对象保留准确声明锚点', await page.locator('#claim .katex').count() > 0);
  check('形式对象移除讲解与 Lean 教学面板', !(await page.locator('main.workspace').innerText()).includes('选择一种讲解'));
  await page.goto(app.origin + '/learning-nodes/learn%3Agroup%3Ainjective-proof', {waitUntil:'networkidle'});
  check('阅读节点投影准确对象而不显示证明正文', await page.locator('.master-variant').count() > 0 && !(await page.locator('main.workspace').innerText()).includes('概括证明'));
  check('多对象声明没有重复 DOM id', await page.evaluate(() => { const ids=[...document.querySelectorAll('.master-content [id]')].map(e=>e.id); return new Set(ids).size===ids.length; }));
  await page.goto(app.origin + '/network?nodes=limit%3Alimit-ed,limit%3Aseq-conv', {waitUntil:'networkidle'});
  const svgNode = page.locator('[data-node="limit:limit-ed"]').first(); await svgNode.waitFor();
  await svgNode.focus();
  await page.locator('.network-node-info [data-master-content]').first().waitFor();
  check('网络悬停共享压缩内容', await page.locator('.network-node-info [data-master-content]').count() > 0);
  check('模式没有改变网络中的节点集合', await page.locator('.network-node[data-node]').count() === 2);
  await svgNode.click({force:true});
  const nodeLink = page.locator('.floating-panel[aria-label="节点详情"] a[href*="from=network"]').first();
  await nodeLink.click();
  await page.locator('.master-node-page').waitFor();
  await page.getByRole('link',{name:'返回网络',exact:true}).click();
  await page.locator('.network-node[data-node]').first().waitFor();
  check('Master 阅读可返回原网络视图', await page.locator('.network-node[data-node]').count() === 2);
  await page.goto(app.origin + '/en/nodes/limit%3Alimit-ed', {waitUntil:'networkidle'});
  check('换语言保留模式且直觉有英文', await page.locator('#reading-mode-select').inputValue() === 'master');
  await page.locator('.master-intuition-trigger').first().hover(); await page.getByRole('tooltip').waitFor();
  check('已提供的英文直觉正常显示', (await page.getByRole('tooltip').innerText()).includes('tolerance'));
  await page.keyboard.press('Escape');
  await page.goto(app.origin + '/en/objects/obj%3Agroup%3Aleft-mul', {waitUntil:'networkidle'});
  check('英文站对尚未翻译的对象说明标明缺译', await page.locator('.master-content .i18n-pending-note').count() > 0);
  check('切换期间个人存储保留', await page.evaluate(() => localStorage.getItem('master-private-sentinel') === 'personal note unchanged'));

  const mobile = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  await mobile.addInitScript(() => localStorage.setItem('mcs-reading-mode-v1','master'));
  const phone = await mobile.newPage(); phone.on('pageerror',error=>errors.push(error.message));
  await phone.goto(app.origin + '/nodes/limit%3Alimit-ed',{waitUntil:'networkidle'});
  check('手机公式不会撑宽整页', await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  await phone.locator('.master-intuition-trigger').first().tap(); await phone.getByRole('tooltip').waitFor();
  check('触屏点击可打开直觉提示', await phone.getByRole('tooltip').isVisible());
  const box=await phone.getByRole('tooltip').boundingBox(); check('触屏提示不越出视口', box.x>=0&&box.x+box.width<=390);
  await phone.screenshot({path:resolve(artifacts,'master-limit-mobile.png'),fullPage:true});
  await phone.getByRole('heading',{level:1}).tap();
  for (const path of ['/nodes/top%3Atopological-manifold','/nodes/dg%3Atangent-bundle','/objects/obj%3Agroup%3Ainjective','/learning-nodes/learn%3Agroup%3Ainjective-proof']) {
    await phone.goto(app.origin + path,{waitUntil:'networkidle'});
    check(`手机公共入口无整页溢出：${path}`, await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  }
  await phone.goto(app.origin + '/nodes/limit%3Alimit-ed',{waitUntil:'networkidle'});
  await phone.locator('#reading-mode-select').selectOption('normal');
  await phone.locator('#node-formal-statement').waitFor();
  check('切回普通模式恢复完整阅读', await phone.locator('#node-reading').count() > 0);
  await mobile.close();
  const privateVault = resolve(artifacts, 'private-vault');
  await mkdir(privateVault, {recursive:true});
  await writeFile(resolve(privateVault, 'Sentinel.md'), '# 私人笔记验收\n\n动机、证明和应用都是我的原文。\n\n$\\sum_{k=1}^n k$\n');
  await page.goto(app.origin + '/library', {waitUntil:'networkidle'});
  await page.evaluate(() => { window.showDirectoryPicker = undefined; });
  await page.locator('input[webkitdirectory]').setInputFiles(privateVault);
  await page.getByRole('button', {name:'预览变更',exact:true}).click();
  await page.locator('.library-diff').waitFor();
  await page.getByRole('button', {name:'导入到当前浏览器',exact:true}).click();
  await page.locator('.vault-document .katex').first().waitFor();
  const privateText = await page.locator('.vault-document').first().innerText();
  check('Master 下个人笔记仍显示完整原文', privateText.includes('动机、证明和应用都是我的原文。'));
  await page.locator('#reading-mode-select').selectOption('normal');
  check('模式切换不改变个人笔记', await page.locator('.vault-document').first().innerText() === privateText);
  check('Master 阅读不写学习记录', writes.length === 0);
  check('浏览器无渲染异常', errors.length === 0);
  console.log(`Master browser acceptance passed; screenshots: ${artifacts}`);
} finally { await browser?.close(); await app.cleanup(); }
