const parseEntry = ([id, en, zh, noteZh, noteEn, page, msc = [], branches = [], aliases = []]) => {
  const [partId, number] = id.split('.');
  return Object.freeze({
    id,
    part: partId,
    number: Number(number),
    title: Object.freeze({ zh, en }),
    note: Object.freeze({ zh: noteZh, en: noteEn }),
    page,
    msc: Object.freeze([...msc]),
    branches: Object.freeze([...branches]),
    aliases: Object.freeze([...aliases]),
  });
};

export const MCS_APPLIED_ENTRIES = Object.freeze(RAW.map(parseEntry));

const BY_ID = new Map(MCS_APPLIED_ENTRIES.map(entry => [entry.id, entry]));
const BY_PART = new Map(APPLIED_PARTS.map(partEntry => [partEntry.id, partEntry]));

export const appliedEntry = id => BY_ID.get(id) ?? null;
export const appliedPart = id => BY_PART.get(id) ?? null;

const normalize = value => String(value ?? '').normalize('NFKC').toLocaleLowerCase();
const compact = value => normalize(value).replace(/[\s.·]/g, '');

/** 词项匹配：去掉空白与点号后同时比对文本和紧缩 ID，支持 IV.18 / iv18。 */
export function normalizeAppliedQuery(value) {
  return normalize(value).trim();
}

const SEARCH = new Map(MCS_APPLIED_ENTRIES.map(entry => [
  entry.id,
  normalize([
    entry.id,
    entry.title.zh,
    entry.title.en,
    entry.note.zh,
    entry.note.en,
    ...entry.aliases,
    ...entry.msc,
    BY_PART.get(entry.part)?.title.zh ?? '',
    BY_PART.get(entry.part)?.title.en ?? '',
  ].join(' ')),
]));

export function filterApplied({ part, msc, branch, query = '', mappedOnly = false } = {}) {
  const search = normalizeAppliedQuery(query);
  const compactSearch = compact(query);
  return MCS_APPLIED_ENTRIES.filter(entry => (
    (!part || entry.part === part)
    && (!msc || entry.msc.includes(msc))
    && (!branch || entry.branches.includes(branch))
    && (!mappedOnly || entry.branches.length > 0)
    && (!search || (SEARCH.get(entry.id) ?? '').includes(search) || compact(entry.id).includes(compactSearch))
  ));
}

export const appliedForBranch = branchId => MCS_APPLIED_ENTRIES.filter(entry => entry.branches.includes(branchId));
export const appliedForMsc = code => MCS_APPLIED_ENTRIES.filter(entry => entry.msc.includes(code));

export function appliedRelated(entry, limit = 4) {
  if (!entry) return { prev: null, next: null, sameMsc: [], sameBranch: [] };
  const siblings = MCS_APPLIED_ENTRIES.filter(item => item.part === entry.part);
  const index = siblings.findIndex(item => item.id === entry.id);
  const score = item => item.msc.filter(code => entry.msc.includes(code)).length;
  const sameMsc = MCS_APPLIED_ENTRIES
    .filter(item => item.id !== entry.id && score(item) > 0)
    .sort((a, b) => score(b) - score(a) || MCS_APPLIED_ENTRIES.indexOf(a) - MCS_APPLIED_ENTRIES.indexOf(b))
    .slice(0, limit);
  const sameBranch = MCS_APPLIED_ENTRIES
    .filter(item => item.id !== entry.id && item.branches.some(id => entry.branches.includes(id)))
    .slice(0, limit);
  return {
    prev: index > 0 ? siblings[index - 1] : null,
    next: index >= 0 && index < siblings.length - 1 ? siblings[index + 1] : null,
    sameMsc,
    sameBranch,
  };
}

export function appliedCitation(entry, locale = 'zh') {
  if (!entry) return '';
  const section = `${entry.part}.${entry.number}`;
  return locale === 'en'
    ? `Higham, N. J. (ed.). The Princeton Companion to Applied Mathematics. Princeton University Press, 2015, ${section}, p. ${entry.page}.`
    : `Higham, N. J.（编）. The Princeton Companion to Applied Mathematics. Princeton University Press, 2015, ${section}，p. ${entry.page}。`;
}

export function appliedCounts() {
  const parts = Object.fromEntries(APPLIED_PARTS.map(entry => [entry.id, 0]));
  const msc = {};
  let mapped = 0;
  for (const entry of MCS_APPLIED_ENTRIES) {
    parts[entry.part] = (parts[entry.part] ?? 0) + 1;
    if (entry.branches.length) mapped += 1;
    for (const code of entry.msc) msc[code] = (msc[code] ?? 0) + 1;
  }
  return { total: MCS_APPLIED_ENTRIES.length, parts, mapped, msc };
}

/**
 * 结构与数据自检；`branchIds`/`mscCodes` 由调用方传入（测试用真实地图与
 * MSC_2020 构造），这样本模块不反向依赖地图生成器。
 */
export function validateAppliedIndex({ branchIds = null, mscCodes = null } = {}) {
  const problems = [];
  const ids = new Set();
  const counts = Object.fromEntries(APPLIED_PARTS.map(entry => [entry.id, 0]));
  let lastPart = null;
  let lastPage = 0;
  for (const entry of MCS_APPLIED_ENTRIES) {
    if (ids.has(entry.id)) problems.push(`duplicate id ${entry.id}`);
    ids.add(entry.id);
    if (!BY_PART.has(entry.part)) problems.push(`unknown part ${entry.id}`);
    if (!entry.title.zh || !entry.title.en) problems.push(`missing title ${entry.id}`);
    if (!entry.note.zh || !entry.note.en) problems.push(`missing note ${entry.id}`);
    if (/[\u3400-\u9fff]/.test(entry.title.en) || /[\u3400-\u9fff]/.test(entry.note.en)) {
      problems.push(`Han characters in English fields ${entry.id}`);
    }
    if (!Number.isInteger(entry.page) || entry.page < 1 || entry.page > 963) problems.push(`bad page ${entry.id}`);
    if (entry.page < lastPage) problems.push(`page decreases at ${entry.id}`);
    if (entry.part !== lastPart) {
      if (counts[entry.part]) problems.push(`non-contiguous part ${entry.part}`);
      const expected = BY_PART.get(entry.part)?.firstPage;
      if (expected && entry.page !== expected) problems.push(`part ${entry.part} starts at ${entry.page}, expected ${expected}`);
      lastPart = entry.part;
    }
    lastPage = entry.page;
    counts[entry.part] += 1;
    if (entry.msc.length > 3) problems.push(`too many MSC codes ${entry.id}`);
    if (mscCodes && entry.msc.some(code => !mscCodes.has(code))) problems.push(`unknown MSC code ${entry.id}`);
    if (branchIds && entry.branches.some(id => !branchIds.has(id))) problems.push(`unknown branch ${entry.id}`);
  }
  for (const partEntry of APPLIED_PARTS) {
    if (counts[partEntry.id] !== partEntry.count) {
      problems.push(`part ${partEntry.id} has ${counts[partEntry.id]}, expected ${partEntry.count}`);
    }
  }
  if (MCS_APPLIED_ENTRIES.length !== APPLIED_PARTS.reduce((sum, entry) => sum + entry.count, 0)) {
    problems.push('total does not match part counts');
  }
  return problems;
}
